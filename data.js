// Helper functions for scoring calculation
function calculateCriterionWeightedScore(rawScore, weight) {
  if (!rawScore || rawScore <= 0) return 0;
  return Number(((rawScore / 5) * weight).toFixed(2));
}

function calculateTotalScores(scores) {
  let rawTotal = 0;
  let weightedTotal = 0;

  ASSESSMENT_CRITERIA.forEach(c => {
    const raw = Number(scores[c.id]) || 0;
    rawTotal += raw;
    weightedTotal += (raw / 5) * c.weight;
  });

  return {
    rawTotal: rawTotal,
    maxRawTotal: 30,
    weightedTotal: Number(weightedTotal.toFixed(2)),
    maxWeightedTotal: 100
  };
}

